import { exec } from "child_process";
import { access, readFile, writeFile } from "fs/promises";
import { join } from "path";
import { MINECRAFT_SERVER_DIR } from "./minecraft.config";

// The installer unpacks a few hundred megabytes of libraries, so give it room
const INSTALL_TIMEOUT_MS = 20 * 60 * 1000;

const fileExists = async (path: string) => {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
};

/**
 * Reads the NeoForge version the pack expects out of startserver.sh.
 */
export const getNeoForgeVersion = async (): Promise<string | null> => {
  try {
    const script = await readFile(
      join(MINECRAFT_SERVER_DIR, "startserver.sh"),
      "utf8",
    );

    return script.match(/^NEOFORGE_VERSION=(\S+)/m)?.[1] ?? null;
  } catch (error) {
    console.error("Failed to read NeoForge version from startserver.sh:", error);
    return null;
  }
};

/**
 * A version of NeoForge is only usable once its arg file has been generated by
 * the installer. startserver.sh only checks that a `libraries` directory exists
 * at all, so it happily skips installing after a pack update bumps the version.
 */
export const isNeoForgeInstalled = (version: string) =>
  fileExists(
    join(
      MINECRAFT_SERVER_DIR,
      "libraries/net/neoforged/neoforge",
      version,
      "unix_args.txt",
    ),
  );

const downloadInstaller = async (version: string, installerPath: string) => {
  const url = `https://maven.neoforged.net/releases/net/neoforged/neoforge/${version}/neoforge-${version}-installer.jar`;
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(
      `Failed to download NeoForge ${version} installer: ${response.status} ${response.statusText}`,
    );
  }

  await writeFile(installerPath, Buffer.from(await response.arrayBuffer()));
};

const runInstaller = (installerPath: string) =>
  new Promise<void>((resolve, reject) => {
    exec(
      `java -jar "${installerPath}" -installServer`,
      {
        cwd: MINECRAFT_SERVER_DIR,
        timeout: INSTALL_TIMEOUT_MS,
        maxBuffer: 10 * 1024 * 1024,
      },
      (error, stdout, stderr) => {
        if (error) {
          console.error("NeoForge installer failed:", stderr || stdout);
          reject(error);
        } else {
          resolve();
        }
      },
    );
  });

/**
 * Installs NeoForge if the version the pack expects isn't present yet,
 * downloading the installer first when it's missing.
 *
 * @returns the expected version and whether an install actually ran
 */
export const ensureNeoForgeInstalled = async (
  onStatus?: (message: string) => void | Promise<void>,
): Promise<{ version: string | null; didInstall: boolean }> => {
  const version = await getNeoForgeVersion();

  if (!version) {
    // Nothing to verify against - let startserver.sh do whatever it does
    return { version: null, didInstall: false };
  }

  if (await isNeoForgeInstalled(version)) {
    return { version, didInstall: false };
  }

  const installerPath = join(
    MINECRAFT_SERVER_DIR,
    `neoforge-${version}-installer.jar`,
  );

  if (!(await fileExists(installerPath))) {
    await onStatus?.(`Downloading the NeoForge ${version} installer...`);
    await downloadInstaller(version, installerPath);
  }

  await onStatus?.(
    `Installing NeoForge ${version}, this can take a few minutes...`,
  );
  await runInstaller(installerPath);

  if (!(await isNeoForgeInstalled(version))) {
    throw new Error(
      `NeoForge ${version} installer finished but ${version}/unix_args.txt is still missing`,
    );
  }

  return { version, didInstall: true };
};
