/**
 * Bridging in-game chat to Fini.
 *
 * In-game chat never reaches the server log on this pack - NoChatReports is
 * installed with `convertToGameMessage`, which turns player chat into system
 * messages, and nothing writes a `<name> message` line. Verified by grepping
 * every archived log back to April: not one chat line.
 *
 * KubeJS *can* see chat though, through `PlayerEvents.chat`, confirmed in game.
 * So the bridge is: a KubeJS script echoes matching messages to the console
 * with a marker, and this side reads them back out of latest.log, which the
 * repo already knows how to tail safely across log rotation.
 *
 * The alternative was writing files from Rhino via Java interop, which is both
 * fiddlier and harder to debug than a log line.
 */

/** Prefix the KubeJS script writes, and this side matches on. */
export const CHAT_MARKER = "[FINI-CHAT]";

/** What the bot was asked, and who asked. */
export type ChatRequest = {
  player: string;
  /** The message with the trigger phrase removed. */
  message: string;
};

/*
 * `[FINI-CHAT] <player> :: <message>`
 *
 * A double colon separates the two because usernames cannot contain one, so
 * nothing a player types can forge a new field.
 */
const CHAT_LINE = /\[FINI-CHAT\]\s*([A-Za-z0-9_]{1,16})\s*::\s*(.*)$/;

/**
 * Pulls chat requests out of a chunk of log text.
 *
 * Tolerates partial lines, since the caller reads byte ranges that can land
 * mid-line, by ignoring anything that doesn't match.
 */
export const parseChatRequests = (
  logText: string,
  trigger: string,
): ChatRequest[] => {
  const requests: ChatRequest[] = [];

  for (const line of logText.split("\n")) {
    const match = line.match(CHAT_LINE);
    if (!match) continue;

    const player = match[1];
    const raw = match[2].trim();
    if (raw.length === 0) continue;

    // Strip the trigger phrase, however it was capitalised
    const message = raw.toLowerCase().startsWith(trigger.toLowerCase())
      ? raw.slice(trigger.length).trim()
      : raw;

    requests.push({ player, message });
  }

  return requests;
};

/**
 * Splits a reply into `tellraw`-sized pieces.
 *
 * Minecraft drops chat lines over 256 characters, and an AI reply is routinely
 * longer, so it has to be broken up. Splits on whitespace to avoid cutting
 * words in half, and hard-splits anything longer than a whole chunk.
 */
export const splitForChat = (reply: string, limit = 200): string[] => {
  const words = reply.replace(/\s+/g, " ").trim().split(" ");
  if (words.length === 0 || words[0] === "") return [];

  const chunks: string[] = [];
  let current = "";

  for (const word of words) {
    // A single word longer than the limit has to be cut
    if (word.length > limit) {
      if (current) {
        chunks.push(current);
        current = "";
      }
      for (let i = 0; i < word.length; i += limit) {
        chunks.push(word.slice(i, i + limit));
      }
      continue;
    }

    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length > limit) {
      chunks.push(current);
      current = word;
    } else {
      current = candidate;
    }
  }

  if (current) chunks.push(current);
  return chunks;
};

/**
 * Renders the KubeJS script that echoes matching chat to the console.
 *
 * Generated rather than hand-written so the repo stays the source of truth -
 * `kubejs/` is deleted by every modpack update.
 *
 * Note it does not cancel the message. Everyone should still see what was
 * asked, exactly as they would any other chat.
 */
export const renderChatScript = (args: { trigger: string }): string => {
  const trigger = args.trigger.toLowerCase();

  return `// GENERATED by scripts/apply-bot-chat.ts - edit that, not this.
//
// Echoes chat beginning with "${trigger}" to the console, where Fini reads it
// out of latest.log. In-game chat is not otherwise logged at all on this pack:
// NoChatReports' convertToGameMessage turns it into system messages, and no
// \`<name> message\` line is ever written.
//
// The message is passed through untouched - everyone still sees it.

var CHAT_TRIGGER = "${trigger}";

PlayerEvents.chat(function (event) {
  try {
    var message = String(event.message);
    if (message.toLowerCase().indexOf(CHAT_TRIGGER) !== 0) return;

    // Double colon as the separator: usernames cannot contain one, so nothing
    // typed in chat can forge a field
    console.info(
      "[FINI-CHAT] " + event.player.username + " :: " + message,
    );
  } catch (e) {
    console.info("[FINI-CHAT-ERROR] " + e);
  }
});
`;
};
