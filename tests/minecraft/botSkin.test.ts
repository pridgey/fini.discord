import { describe, expect, it } from "bun:test";
import {
  buildTexturesValue,
  parseSkinSpec,
  readTexturesValue,
  renderSkinScript,
  SkinSpecError,
} from "../../utilities/minecraft/botSkin";

describe("parseSkinSpec", () => {
  it("parses an account spec", () => {
    expect(parseSkinSpec("account:Dinnerbone")).toEqual({
      kind: "account",
      name: "Dinnerbone",
    });
  });

  it("defaults a url spec to the classic model", () => {
    expect(parseSkinSpec("url:https://example.com/fini.png")).toEqual({
      kind: "url",
      url: "https://example.com/fini.png",
      model: "classic",
    });
  });

  it("reads the slim model off the fragment", () => {
    expect(parseSkinSpec("url:https://example.com/fini.png#slim")).toEqual({
      kind: "url",
      url: "https://example.com/fini.png",
      model: "slim",
    });
  });

  /** bun's `toThrow` types don't take a custom error class, so check directly. */
  const expectSpecError = (spec: string) => {
    let thrown: unknown = null;
    try {
      parseSkinSpec(spec);
    } catch (error) {
      thrown = error;
    }
    expect(thrown).toBeInstanceOf(SkinSpecError);
  };

  it("rejects specs it cannot understand", () => {
    expectSpecError("Dinnerbone");
    expectSpecError("skin:Dinnerbone");
    expectSpecError("url:not-a-url");
    expectSpecError("url:https://x/y.png#chunky");
    // Too short, and illegal characters
    expectSpecError("account:ab");
    expectSpecError("account:has space");
  });
});

describe("buildTexturesValue", () => {
  const identity = {
    profileId: "7b747311-bb5f-4cf2-b47a-c037928e0824",
    profileName: "FINI",
  };

  it("round-trips a classic skin, with no metadata", () => {
    const value = buildTexturesValue({
      url: "https://example.com/fini.png",
      model: "classic",
      ...identity,
      timestamp: 1700000000000,
    });
    const decoded = readTexturesValue(value);

    expect(decoded.textures.SKIN?.url).toBe("https://example.com/fini.png");
    // Mojang omits metadata for classic, so a payload claiming it looks wrong
    expect(decoded.textures.SKIN?.metadata).toBeUndefined();
    expect(decoded.timestamp).toBe(1700000000000);
  });

  it("marks the slim model in metadata", () => {
    const value = buildTexturesValue({
      url: "https://example.com/fini.png",
      model: "slim",
      ...identity,
    });
    expect(readTexturesValue(value).textures.SKIN?.metadata?.model).toBe("slim");
  });

  // Real payloads carry the id undashed
  it("strips dashes from the profile id", () => {
    const value = buildTexturesValue({
      url: "https://example.com/fini.png",
      model: "classic",
      ...identity,
    });
    expect(readTexturesValue(value).profileId).toBe(
      "7b747311bb5f4cf2b47ac037928e0824",
    );
  });
});

describe("renderSkinScript", () => {
  const base = {
    botName: "Fini",
    description: "test skin",
  };

  it("emits the signature when the skin is signed", () => {
    const script = renderSkinScript({
      ...base,
      textures: { value: "VALUE", signature: "SIGNATURE" },
    });
    expect(script).toContain('var SKIN_SIG =\n  "SIGNATURE";');
    expect(script).toContain('var SKIN_VALUE =\n  "VALUE";');
  });

  /*
   * Unsigned has to come through as a literal null, because the script picks
   * the one-argument Property constructor off that check - passing an empty
   * string would build a property claiming a signature it doesn't have.
   */
  it("emits a null signature for an unsigned skin", () => {
    const script = renderSkinScript({
      ...base,
      textures: { value: "VALUE", signature: null },
    });
    expect(script).toContain("var SKIN_SIG = null;");
    expect(script).not.toContain('var SKIN_SIG =\n  "');
  });

  it("lowercases the bot name, since the script compares lowercased", () => {
    const script = renderSkinScript({
      ...base,
      botName: "FiNi",
      textures: { value: "V", signature: null },
    });
    expect(script).toContain('var BOT_NAME = "fini";');
  });

  // The file lands in the modpack, which a pack update deletes - so it must
  // say where it came from
  it("marks itself generated and names its source", () => {
    const script = renderSkinScript({
      ...base,
      textures: { value: "V", signature: null },
    });
    expect(script).toContain("GENERATED by scripts/apply-bot-skin.ts");
    expect(script).toContain("test skin");
  });
});
