import { describe, expect, it } from "bun:test";
import {
  parseChatRequests,
  renderChatScript,
  splitForChat,
} from "../../modules/minecraft/botChat";

const TRIGGER = "hey fini";

// Shaped like a real server log line, timestamp and KubeJS prefix included
const line = (body: string) =>
  `[04Oct2026 16:30:00.123] [Server thread/INFO] [KubeJS Server/]: server_scripts:fini_chat.js#20: ${body}`;

describe("parseChatRequests", () => {
  it("reads the player and strips the trigger", () => {
    const text = line("[FINI-CHAT] Pridgey :: hey fini what is a creeper");
    expect(parseChatRequests(text, TRIGGER)).toEqual([
      { player: "Pridgey", message: "what is a creeper" },
    ]);
  });

  it("strips the trigger whatever its capitalisation", () => {
    const text = line("[FINI-CHAT] Pridgey :: Hey Fini hello there");
    expect(parseChatRequests(text, TRIGGER)[0].message).toBe("hello there");
  });

  it("reads several requests out of one chunk", () => {
    const text = [
      line("[FINI-CHAT] Pridgey :: hey fini first"),
      line("[Server thread/INFO]: unrelated noise"),
      line("[FINI-CHAT] Someone_Else :: hey fini second"),
    ].join("\n");

    expect(parseChatRequests(text, TRIGGER).map((r) => r.player)).toEqual([
      "Pridgey",
      "Someone_Else",
    ]);
  });

  /*
   * The caller reads byte ranges out of latest.log, so a chunk can begin or
   * end mid-line. Anything that doesn't match is simply skipped.
   */
  it("ignores partial and unrelated lines", () => {
    const text = [
      "ad7fb322d3b1a1842da8dbf5e930ef9d1986",
      line("[FINI-CHAT] Pridgey :: hey fini intact"),
      "[04Oct2026 16:30:01.000] [Server thread/INFO] [KubeJS Server/]: [FINI-CH",
    ].join("\n");

    expect(parseChatRequests(text, TRIGGER)).toEqual([
      { player: "Pridgey", message: "intact" },
    ]);
  });

  it("drops a request with nothing after the trigger", () => {
    expect(parseChatRequests(line("[FINI-CHAT] Pridgey :: "), TRIGGER)).toEqual(
      [],
    );
  });

  // A player typing "::" must not be able to invent a username
  it("does not let chat content forge a field", () => {
    const text = line("[FINI-CHAT] Pridgey :: hey fini Nefarious :: pretend");
    const requests = parseChatRequests(text, TRIGGER);
    expect(requests).toHaveLength(1);
    expect(requests[0].player).toBe("Pridgey");
    expect(requests[0].message).toBe("Nefarious :: pretend");
  });

  it("finds nothing in a log with no chat", () => {
    expect(parseChatRequests(line("Done (2.3s)! For help"), TRIGGER)).toEqual(
      [],
    );
  });
});

describe("splitForChat", () => {
  // Minecraft drops chat lines over 256 characters
  it("leaves a short reply alone", () => {
    expect(splitForChat("a short answer")).toEqual(["a short answer"]);
  });

  it("splits a long reply on whitespace", () => {
    const reply = Array.from({ length: 60 }, () => "word").join(" ");
    const chunks = splitForChat(reply, 50);

    for (const chunk of chunks) expect(chunk.length).toBeLessThanOrEqual(50);
    // Nothing lost, and no words cut in half
    expect(chunks.join(" ")).toBe(reply);
  });

  it("hard-splits a single word longer than the limit", () => {
    const chunks = splitForChat("x".repeat(120), 50);
    expect(chunks).toHaveLength(3);
    expect(chunks.join("")).toBe("x".repeat(120));
  });

  it("collapses whitespace and handles an empty reply", () => {
    expect(splitForChat("  spaced   out  ")).toEqual(["spaced out"]);
    expect(splitForChat("   ")).toEqual([]);
  });
});

describe("renderChatScript", () => {
  it("embeds the trigger lowercased and marks itself generated", () => {
    const script = renderChatScript({ trigger: "Hey Fini" });
    expect(script).toContain('var CHAT_TRIGGER = "hey fini";');
    expect(script).toContain("GENERATED by scripts/apply-bot-chat.ts");
  });

  // Cancelling would hide the question from everyone else in chat
  it("does not cancel the chat event", () => {
    expect(renderChatScript({ trigger: "hey fini" })).not.toContain("cancel");
  });
});
